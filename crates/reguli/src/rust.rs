//! The Rust code of the rules: the constants of the core's `rules` module that come from the
//! rule files, with the names and types the core uses. `crates/core/codegen.rs` writes it to
//! `$OUT_DIR/reguli.rs`, which `crates/core/src/rules/lists.rs` includes.
use std::fmt::Write;

use crate::{LISTS, List, Rules, Value};

/// The constants of `rules` as Rust code. It holds no comment, so a change to a comment of a
/// rule file changes nothing in it, nor in `RULES_HASH`.
pub fn rust(rules: &Rules) -> String {
    let mut out =
        String::from("// Generated by grafia-reguli from reguli/ (crates/core/codegen.rs): edit reguli/, not this.\n");
    out += "pub const SYLLABIFICATIONS: &[(&str, &[&str])] = &[\n";
    for (word, readings) in &rules.silabisiri {
        let _ = writeln!(out, "    ({:?}, &[{}]),", word.text, quoted(readings));
    }
    out += "];\n";
    out += "pub const OBSOLETE: &[(&str, &str, &str, bool)] = &[\n";
    for o in &rules.lemme {
        let (lema, actuala, tulpina) = (&o.lema.text, &o.actuala.text, &o.tulpina.text);
        let _ = writeln!(out, "    ({lema:?}, {actuala:?}, {tulpina:?}, {}),", o.fara_forme);
    }
    out += "];\n";
    for list in &LISTS {
        let mut words = written(rules, list).to_vec();
        // the words it holds from another list, which it doesn't write again (the names in -oe)
        if let Some((key, ending)) = list.plus {
            let there = crate::list(list.file, key).expect("plus names a list of the same file");
            words.extend(
                written(rules, there)
                    .iter()
                    .filter(|w| w.text.ends_with(ending))
                    .cloned(),
            );
        }
        let _ = writeln!(out, "pub const {}: &[&str] = &[{}];", list.constant, quoted(&words));
    }
    out
}

/// The words written in `list`: rules come only from files with every list read.
fn written<'r>(rules: &'r Rules, list: &List) -> &'r [Value] {
    rules
        .lists
        .get(list.constant)
        .unwrap_or_else(|| panic!("{} has no words read for {}", list.file, list.key))
}

fn quoted(values: &[Value]) -> String {
    let quoted: Vec<String> = values.iter().map(|v| format!("{:?}", v.text)).collect();
    quoted.join(", ")
}
