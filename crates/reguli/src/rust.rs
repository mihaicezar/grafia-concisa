//! The Rust code of the rules: the constants of the core's `rules` module that come from the
//! rule files, with the names and types the core uses. `crates/core/codegen.rs` writes `rust`'s
//! code to `$OUT_DIR/reguli.rs`, which `crates/core/src/rules/lists.rs` includes, and `meta`'s
//! to `$OUT_DIR/reguli_meta.rs`, which `crates/core/src/rules/tables.rs` includes.
use std::fmt::Write;

use crate::{CONTEXTS, LISTS, List, Rules, TABLES, Value};

/// The constants of `rules` as Rust code: the lists and the tables. It holds no comment, nor
/// any line of a file, so a change to a comment of a rule file changes nothing in it, nor in
/// `RULES_HASH`, which hashes it.
pub fn rust(rules: &Rules) -> String {
    let mut out =
        String::from("// Generated by grafia-reguli from reguli/ (crates/core/codegen.rs): edit reguli/, not this.\n");
    out += "pub const SYLLABIFICATIONS: &[(&str, &[&str])] = &[\n";
    for (word, readings) in &rules.silabisiri {
        let _ = writeln!(out, "    ({:?}, &[{}]),", word.text, quoted(readings));
    }
    out += "];\n";
    out += "pub const OBSOLETE: &[(&str, &str, &str, bool)] = &[\n";
    for o in &rules.leme {
        let (lema, actuala, tulpina) = (&o.lema.text, &o.actuala.text, &o.tulpina.text);
        let _ = writeln!(out, "    ({lema:?}, {actuala:?}, {tulpina:?}, {}),", o.fara_forme);
    }
    out += "];\n";
    for list in &LISTS {
        let mut words = written(rules, list).to_vec();
        // the words it holds from another list, which it doesn't write again (the names in -oe)
        if let Some((key, ending)) = list.plus {
            let there = crate::list(list.file, key).expect("plus names a list of the same file");
            words.extend(
                written(rules, there)
                    .iter()
                    .filter(|w| w.text.ends_with(ending))
                    .cloned(),
            );
        }
        let _ = writeln!(out, "pub const {}: &[&str] = &[{}];", list.constant, quoted(&words));
    }
    for t in &TABLES {
        let pair: Vec<String> = t.pair.chars().map(|c| format!("{c:?}")).collect();
        let _ = writeln!(
            out,
            "pub static {}: Table = Table {{ file: {:?}, pair: [{}], cut: {}, entries: &[",
            t.constant,
            t.file,
            pair.join(", "),
            t.hiat
        );
        for e in entries(rules, t.file) {
            let mut fields = vec![format!("tipar: &[{}]", quoted(&e.tipar))];
            for (key, items) in CONTEXTS.iter().zip(&e.contexts) {
                fields.push(format!("{key}: &[{}]", quoted(items)));
            }
            let _ = writeln!(out, "    Entry {{ {} }},", fields.join(", "));
        }
        out += "] };\n";
    }
    out
}

/// The lines of the rules, for the trace of the core's `syllabify_traced`, as Rust code:
/// `SYLLABIFICATION_LINES`, the line of each word of `SYLLABIFICATIONS`; `TABLES`, the tables;
/// and `ENTRY_LINES`, the line of each entry of each of them. `RULES_HASH` doesn't hash it.
pub fn meta(rules: &Rules) -> String {
    let mut out = String::from(
        "// Generated by grafia-reguli from reguli/ (crates/core/codegen.rs): the lines of the rules, not in RULES_HASH.\n",
    );
    let lines: Vec<String> = rules.silabisiri.iter().map(|(w, _)| w.line.to_string()).collect();
    let _ = writeln!(
        out,
        "pub const SYLLABIFICATION_LINES: &[usize] = &[{}];",
        lines.join(", ")
    );
    let tables: Vec<String> = TABLES.iter().map(|t| format!("&{}", t.constant)).collect();
    let n = TABLES.len();
    let _ = writeln!(out, "pub static TABLES: [&Table; {n}] = [{}];", tables.join(", "));
    let _ = writeln!(out, "pub const ENTRY_LINES: [&[usize]; {n}] = [");
    for t in &TABLES {
        let lines: Vec<String> = entries(rules, t.file).iter().map(|e| e.line.to_string()).collect();
        let _ = writeln!(out, "    &[{}],", lines.join(", "));
    }
    out += "];\n";
    out
}

/// The words written in `list`: rules come only from files with every list read.
fn written<'r>(rules: &'r Rules, list: &List) -> &'r [Value] {
    rules
        .lists
        .get(list.constant)
        .unwrap_or_else(|| panic!("{} has no words read for {}", list.file, list.key))
}

/// The entries of the table in `file`: rules come only from files with every table read.
fn entries<'r>(rules: &'r Rules, file: &str) -> &'r [crate::Entry] {
    rules
        .tables
        .get(file)
        .unwrap_or_else(|| panic!("{file} has no entries read"))
}

fn quoted(values: &[Value]) -> String {
    let quoted: Vec<String> = values.iter().map(|v| format!("{:?}", v.text)).collect();
    quoted.join(", ")
}
